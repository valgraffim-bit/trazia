import { knownSharedWazePlace } from './search-locations.mjs?v=66';
const WAZE_HOSTS = new Set(['waze.com', 'www.waze.com']);

function importError(code) {
  const error = new Error(code);
  error.code = code;
  return error;
}

function coordinates(value) {
  const match = String(value).match(/^\s*([+-]?(?:\d+(?:\.\d*)?|\.\d+))\s*,\s*([+-]?(?:\d+(?:\.\d*)?|\.\d+))\s*$/);
  if (!match) throw importError('WAZE_INVALID_COORDINATES');
  const lat = Number(match[1]);
  const lng = Number(match[2]);
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || Math.abs(lat) > 90 || Math.abs(lng) > 180) throw importError('WAZE_INVALID_COORDINATES');
  return { lat, lng };
}

// Waze also shares /ul/h<geohash> links. Decode the bounded cell center,
// preserving its approximate nature instead of treating it as a street address.
function geohashCenter(hash) {
  const alphabet = '0123456789bcdefghjkmnpqrstuvwxyz';
  if (!/^[0-9bcdefghjkmnpqrstuvwxyz]{8,12}$/.test(hash)) throw importError('WAZE_NO_COORDINATES');
  const lat = [-90, 90];
  const lng = [-180, 180];
  let longitudeBit = true;
  for (const char of hash) {
    const value = alphabet.indexOf(char);
    for (let bit = 4; bit >= 0; bit--) {
      const range = longitudeBit ? lng : lat;
      range[(value >> bit) & 1 ? 0 : 1] = (range[0] + range[1]) / 2;
      longitudeBit = !longitudeBit;
    }
  }
  return { lat: (lat[0] + lat[1]) / 2, lng: (lng[0] + lng[1]) / 2 };
}

export function parseWazeLocation(text) {
  const input = String(text || '').trim();
  // Accept the URL on its own or inside the text generated by Share.
  const match = input.match(/(?:https:\/\/(?:www\.)?(?:waze\.com|waze\.to)(?=[/:?#\s]|$)|waze:\/\/)[^\s<>"']*/i);
  if (!match) return null;
  const link = match[0].replace(/[)\].,;!]+$/, '');
  let url;
  try { url = new URL(link); } catch { throw importError('WAZE_INVALID_LINK'); }
  if (url.protocol !== 'waze:' && (url.protocol !== 'https:' || !WAZE_HOSTS.has(url.hostname.toLowerCase()))) throw importError('WAZE_NO_COORDINATES');
  if (url.username || url.password || url.port) throw importError('WAZE_INVALID_LINK');
  let location;
  let approximate = false;
  let sharedHash;
  let label;
  if (url.searchParams.has('ll')) location = coordinates(url.searchParams.get('ll'));
  else if (url.searchParams.get('to')?.startsWith('ll.')) location = coordinates(url.searchParams.get('to').slice(3));
  else {
    const hash = url.searchParams.get('h') || url.pathname.match(/^\/ul\/h([0-9bcdefghjkmnpqrstuvwxyz]+)\/?$/i)?.[1];
    const placeId = url.searchParams.get('to')?.startsWith('place.') ? url.searchParams.get('to').slice(6) : null;
    const known = knownSharedWazePlace(placeId);
    if (known) {
      location = known.location;
      label = known.label;
    } else if (hash) {
      sharedHash = hash.toLowerCase();
      location = geohashCenter(sharedHash);
      approximate = true;
    } else throw importError('WAZE_NO_COORDINATES');
  }
  // Keep only a canonical coordinate link, discarding tracking and other text.
  const canonical = new URL('https://www.waze.com/ul');
  canonical.searchParams.set(approximate ? 'h' : 'll', approximate ? sharedHash : `${location.lat},${location.lng}`);
  return { location, approximate, link: canonical.toString(), ...(label ? { label } : {}) };
}
